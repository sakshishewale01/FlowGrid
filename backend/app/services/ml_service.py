"""
FlowGrid AI - Machine Learning Prediction Service
=================================================
Executes model inference using the trained scikit-learn pipeline artifact.
Enforces safe handling of missing artifacts, input serialization, and zero database mutations.
"""

from pathlib import Path
from typing import Dict, Any, Optional
import joblib
from fastapi import HTTPException, status

from app.core.logging import get_logger
from app.schemas.ml import DelayPredictionRequest, DelayPredictionResponse

logger = get_logger("ml_service")

# Resolve artifact path relative to backend root
BACKEND_DIR = Path(__file__).resolve().parent.parent.parent
DEFAULT_MODEL_PATH = BACKEND_DIR / "ml" / "models" / "india_delay_pipeline.joblib"


class MLDelayService:
    """
    Service responsible for loading and executing the India delay classification pipeline.
    """

    def __init__(self, model_path: Optional[Path] = None):
        self.model_path = model_path or DEFAULT_MODEL_PATH
        self._cached_pipeline = None

    def _get_pipeline(self):
        """
        Loads the joblib pipeline artifact, caching it in memory.
        Raises 503 SERVICE UNAVAILABLE if the artifact does not exist or fails to load.
        """
        if self._cached_pipeline is not None:
            return self._cached_pipeline

        if not self.model_path.exists():
            logger.error(f"Model artifact not found at {self.model_path}")
            raise HTTPException(
                status_code=status.HTTP_503_SERVICE_UNAVAILABLE,
                detail="Shipment delay prediction model artifact is not available. Please train the model first.",
            )

        try:
            pipeline = joblib.load(self.model_path)
            self._cached_pipeline = pipeline
            logger.info(f"Loaded ML model pipeline from {self.model_path}")
            return self._cached_pipeline
        except Exception as exc:
            logger.error(f"Failed to load ML pipeline artifact from {self.model_path}: {exc}")
            raise HTTPException(
                status_code=status.HTTP_503_SERVICE_UNAVAILABLE,
                detail=f"Unable to initialize shipment delay model: {str(exc)}",
            )

    def predict_delay(self, request: DelayPredictionRequest) -> DelayPredictionResponse:
        """
        Runs model inference on validated shipment features.
        Zero side-effects: Does NOT modify or write records to PostgreSQL.
        """
        pipeline = self._get_pipeline()
        features = request.to_feature_dict()

        try:
            # Predict probability: [prob_class_0, prob_class_1]
            probs = pipeline.predict_proba([features])[0]
            # Predict binary class: 0 or 1
            pred = pipeline.predict([features])[0]

            delay_prob = round(float(probs[1]), 4)
            is_delayed = bool(pred == 1)

            # Assign qualitative risk band
            if delay_prob < 0.25:
                risk_level = "LOW"
            elif delay_prob <= 0.50:
                risk_level = "MEDIUM"
            else:
                risk_level = "HIGH"

            return DelayPredictionResponse(
                is_delayed=is_delayed,
                delay_probability=delay_prob,
                risk_level=risk_level,
                model_version="random_forest_v1_india_synthetic",
                explanation=(
                    "Prototype notice: This prediction is generated by a Random Forest model trained "
                    "on the synthetic India logistics benchmark dataset (1,451 records). Delay labels "
                    "in the underlying dataset do not represent genuine carrier tracking history. "
                    "This model demonstrates architecture and integration readiness, not real-world delay likelihood."
                ),
                features_used=features,
            )
        except Exception as exc:
            logger.error(f"Error during ML model inference: {exc}")
            raise HTTPException(
                status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
                detail=f"Delay prediction computation failed: {str(exc)}",
            )


# Singleton service instance
ml_delay_service = MLDelayService()
